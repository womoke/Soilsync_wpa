export const KENYA_COUNTIES: string[] = Object.keys(KENYA_LOCATIONS).sort()

export function getSubCounties(county: string): string[] {
  if (!county || !KENYA_LOCATIONS[county]) return []
  return Object.keys(KENYA_LOCATIONS[county]).sort()
}

export function getWards(county: string, subCounty: string): string[] {
  if (!county || !subCounty || !KENYA_LOCATIONS[county] || !KENYA_LOCATIONS[county][subCounty]) {
    return []
  }
  return [...KENYA_LOCATIONS[county][subCounty]].sort()
}
